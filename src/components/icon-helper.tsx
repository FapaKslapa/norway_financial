type CategoryIconProps = {
  name: string;
  size?: number;
  className?: string;
};

export function CategoryIcon({
  name,
  size = 16,
  className,
}: CategoryIconProps) {
  const IconComp = iconMap[name] || HelpCircle;
  return <IconComp size={size} className={className} />;
}
